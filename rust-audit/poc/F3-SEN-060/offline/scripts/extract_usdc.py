"""Write src/UsdcCode.sol from a Foundry RPC cache file, with no network access.

Usage: python3 -I scripts/extract_usdc.py ~/.foundry/cache/rpc/xdai/48635154 src/UsdcCode.sol

Takes the runtime code of Gnosis USDC.e (FiatTokenProxy and its FiatTokenV2_2 implementation)
and every proxy storage slot the cache holds. Adapted from R7's extractor
(rust-audit/state/run3/logs/R7-usdc-approve-gas.txt).
"""

import hashlib
import json
import sys

BLOCK = 48635154
PROXY = "0x2a22f9c3b484c3629090FeED35F17Ff8F88f76F0"
IMPL = "0x107CF7fb73EA48D1D200989b156Ce1894d7AfEC7"


def runtime_code(account):
    analyzed = account["code"]["LegacyAnalyzed"]
    code = analyzed["bytecode"].removeprefix("0x")
    # LegacyAnalyzed pads the code for analysis; original_len is the deployed length.
    return code[: 2 * analyzed["original_len"]], analyzed["original_len"]


def word(value):
    return "0x" + format(int(value, 16), "064x")


def main(cache_path, out_path):
    raw = open(cache_path, "rb").read()
    cache = json.loads(raw)
    block = int(cache["meta"]["block_env"]["number"], 16)
    if block != BLOCK:
        sys.exit(f"cache is for block {block}, expected {BLOCK}")
    accounts = {k.lower(): v for k, v in cache["accounts"].items()}
    storage = {k.lower(): v for k, v in cache["storage"].items()}
    proxy_code, proxy_len = runtime_code(accounts[PROXY.lower()])
    impl_code, impl_len = runtime_code(accounts[IMPL.lower()])
    slots = sorted(storage[PROXY.lower()].items(), key=lambda kv: int(kv[0], 16))
    digest = hashlib.sha256(raw).hexdigest()

    print(f"cache {cache_path} sha256 {digest}", file=sys.stderr)
    print(f"block {block} hosts {cache['meta']['hosts']}", file=sys.stderr)
    print(f"proxy len {proxy_len} code_hash {accounts[PROXY.lower()]['code_hash']}", file=sys.stderr)
    print(f"impl len {impl_len} code_hash {accounts[IMPL.lower()]['code_hash']}", file=sys.stderr)
    print(f"proxy storage slots {len(slots)}", file=sys.stderr)
    for slot, value in slots:
        print(f"  {word(slot)} = {word(value)}", file=sys.stderr)

    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "pragma solidity ^0.8.30;",
        "",
        "// Generated by scripts/extract_usdc.py from the Foundry RPC cache for Gnosis block",
        f"// {BLOCK} (sha256 {digest}).",
        "// Gnosis USDC.e: FiatTokenProxy and FiatTokenV2_2 runtime code, and every proxy storage slot",
        "// the cache holds. Do not edit by hand.",
        "library UsdcCode {",
        f"    uint256 internal constant BLOCK = {BLOCK};",
        f"    address internal constant PROXY = {PROXY};",
        f"    address internal constant IMPL = {IMPL};",
        f"    bytes32 internal constant PROXY_CODE_HASH = {accounts[PROXY.lower()]['code_hash']};",
        f"    bytes32 internal constant IMPL_CODE_HASH = {accounts[IMPL.lower()]['code_hash']};",
        "",
        "    function proxyCode() internal pure returns (bytes memory) {",
        f'        return hex"{proxy_code}";',
        "    }",
        "",
        "    function implCode() internal pure returns (bytes memory) {",
        f'        return hex"{impl_code}";',
        "    }",
        "",
        "    function slots() internal pure returns (bytes32[] memory keys, bytes32[] memory values) {",
        f"        keys = new bytes32[]({len(slots)});",
        f"        values = new bytes32[]({len(slots)});",
    ]
    for i, (slot, value) in enumerate(slots):
        lines.append(f"        keys[{i}] = {word(slot)};")
        lines.append(f"        values[{i}] = {word(value)};")
    lines += ["    }", "}", ""]
    with open(out_path, "w") as out:
        out.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
